#include<p18f4520.h>
void main()
{
unsigned char digit[10]={0XE7,0X21,0XCB,0X6B,0X2D,0X6E,0XEE,0X23,0XEF,0X6F};
int i,j,k,l,m;
i=j=k=l=m=0;
TRISA=0X00;
TRISD=0X00;
PORTA=0X00;
while(1)
{
PORTD=digit[i];
PORTAbits.RA0=1;
PORTAbits.RA1=0;
PORTAbits.RA2=0;
PORTAbits.RA3=0;

PORTD=digit[j];
PORTAbits.RA1=1;
PORTAbits.RA0=0;
PORTAbits.RA2=0;
PORTAbits.RA3=0;

PORTD=digit[k];
PORTAbits.RA2=1;
PORTAbits.RA0=0;
PORTAbits.RA1=0;
PORTAbits.RA3=0;

PORTD=digit[l];
PORTAbits.RA3=1;
PORTAbits.RA0=0;
PORTAbits.RA1=0;
PORTAbits.RA2=0;
{
m++;
if(m==2000)
{
l++;
m=0;
}
if(l==10)
{
k++;
l=0;
}
if(k==10)
{
j++;
k=0;
l=0;
}
if(j==10)
{
i++;
j=0;
k=0;
l=0;
}
if(i==10)
{
i=0;
j=0;
k=0;
l=0;
}
}
}
}